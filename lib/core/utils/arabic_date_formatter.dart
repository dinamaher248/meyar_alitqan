class ArabicDateFormatter {
  ArabicDateFormatter._();

  static const List<String> _months = [
    "يناير",
    "فبراير",
    "مارس",
    "أبريل",
    "مايو",
    "يونيو",
    "يوليو",
    "أغسطس",
    "سبتمبر",
    "أكتوبر",
    "نوفمبر",
    "ديسمبر",
  ];

  static String monthName(int month) => _months[month - 1];
}
